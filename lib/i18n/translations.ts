export function translateText(value: string, language: 'en' | 'id'): string {
  if (language === 'en') return value;
  const trimmed = value.trim();
  const translated = idTranslations[trimmed];
  if (translated) return value.replace(trimmed, translated);
  const showing = trimmed.match(/^Showing (\d+) of (\d+) (.+)$/);
  if (showing) return `Menampilkan ${showing[1]} dari ${showing[2]} ${translateText(showing[3], 'id')}`;
  const unread = trimmed.match(/^You have (\d+) unread notifications$/);
  if (unread) return `Ada ${unread[1]} notifikasi belum dibaca`;
  return value;
}
